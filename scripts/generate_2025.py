def create_event(date_str: str, period: int, subject: str) -> Event:
    """イベントを作成"""
    event = Event()
    
    date = datetime.strptime(date_str, '%Y/%m/%d')
    
    start_str, end_str = TIME_SLOTS[period]
    start_time = TZ.localize(datetime.combine(
        date.date(),
        datetime.strptime(start_str, '%H:%M').time()
    ))
    end_time = TZ.localize(datetime.combine(
        date.date(),
        datetime.strptime(end_str, '%H:%M').time()
    ))
    
    event.add('summary', subject)
    event.add('dtstart', start_time)
    event.add('dtend', end_time)
    event.add('dtstamp', datetime.now(TZ))
    
    uid = f"{date_str.replace('/', '')}-p{period}-{abs(hash(subject)) % 100000}@okayama-med"
    event.add('uid', uid)
    
    return event


def create_calendar() -> Calendar:
    """カレンダーを作成"""
    cal = Calendar()
    cal.add('prodid', f'-//岡山大学医学部 {YEAR}年度 学士編入時間割//')
    cal.add('version', '2.0')
    cal.add('calscale', 'GREGORIAN')
    cal.add('method', 'PUBLISH')
    cal.add('x-wr-calname', f'学士編入時間割')
    cal.add('x-wr-timezone', 'Asia/Tokyo')
    
    for date_str, period, subject in TIMETABLE_DATA:
        event = create_event(date_str, period, subject)
        cal.add_component(event)
    
    return cal


def main():
    print("=" * 60)
    print(f"岡山大学医学部 {YEAR}年度 学士編入 時間割 ICS生成")
    print("=" * 60)
    
    calendar = create_calendar()
    
    print(f"\n総イベント数: {len(TIMETABLE_DATA)} 件")
    
    # 科目別カウント
    subjects = [re.sub(r'\d+$', '', s) for _, _, s in TIMETABLE_DATA]
    counts = Counter(subjects)
    
    print("\n科目別イベント数:")
    for subject, count in sorted(counts.items()):
        print(f"  - {subject}: {count}件")
    
    
    # ファイル出力
    output_file = Path(f"gakushi_timetable_{YEAR}.ics")
    with open(output_file, 'wb') as f:
        f.write(calendar.to_ical())
    
    print(f"\n出力: {output_file}")
    print("\n完了！")


